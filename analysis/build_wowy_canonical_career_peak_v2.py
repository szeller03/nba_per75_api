for name in ['Wilt Chamberlain','Michael Jordan','LeBron James','Nikola Jokic']:
 c=career[career.Player.str.casefold()==name.casefold()]
 pk=[x for x in peak_rows if x['player_name'].casefold()==name.casefold()]
 print(name,'career',c[['Career_SDI_v4','Career_defense','Career_impact_value','Career_WOWY_Defense_Percentile','Career_WOWY_Net_Percentile']].to_dict('records') if not c.empty else None,'peak',[(x['peak_start_year'],x['peak_end_year'],x['peak_sdi'],x['statistics'].get('WOWY_Offense'),x['statistics'].get('WOWY_Defense'),x['statistics'].get('WOWY_Net')) for x in pk])

(Path(DATA)/'SDI_V4_WOWY_CAREER_PEAK_BUILD_REPORT_V1.json').write_text(json.dumps({'career_rows':len(career),'peak_rows':len(peak_rows),'formula':'locked SDI v4 weights with WOWY integrated into Creation/Playmaking, Defense, Impact/Value','headshot_policy':'NBA CDN plus project-added verified headshots only; no Basketball-Reference URLs'},indent=2))
